"""Emit stage: the properties that survived become ordinary tests of the target project.

For each statement whose check status is BOUNDED_HOLDS (and, when a judge ran, each
repaired statement adjudication accepted) this stage writes pytest functions into
`<target>/tests/autoform_generated/test_<module>.py`, where `<target>` is the analysed
source tree (`--emit-dir` overrides the directory):

  concrete tests   one per domain point of the check stage whose real CPython outcome
                   satisfies the statement's `pre` and `post` *as evaluated by Lean on that
                   outcome* (one `#eval` per function, over the same `pre_`/`post_`
                   definitions the check stage certified). The test rebuilds the arguments
                   (receivers from their recorded state, without `__init__`), calls the real
                   function and asserts the recorded outcome exactly (value or exception
                   class; for a `#post` statement also the receiver's state after the call).
  hypothesis test  one per statement whose binders are all Int/Nat/Bool/String: `@given`
                   over the typed binders, `assume(pre)`, `assert post`, with `pre`/`post`
                   translated to Python by `pyprop`. The translation is accepted only if it
                   agrees with Lean's evaluation on every concrete point that has a real
                   outcome, and at least one of those points satisfied `pre`.

Every test's docstring carries the English property, the statement and function, the
evidence level (kernel-proved, or bounded over N points), the run id, the model name and
the formalize prompt hash. The emitted files are then run with the real interpreter
(`AUTOFORM_PYTHON`, else this one) and the result of every test is recorded in
`emit.json`; a failing emitted test is a finding of this stage (status FAILING), never
dropped. Refuted, uncheckable and unelaborated statements are listed by name with the
reason they were not emitted.

Deduplication: the target's own suite (`<target>/tests`, `<target>/test`, and every
`--tests DIR`) is traced the way the model stage traces it (`model.trace_tests`, no
per-function cap), and a concrete test whose argument tuple the suite already produced is
not emitted; the count is recorded per statement and in total. The generated directory is
removed before tracing so a previous emission never deduplicates itself.

What this stage does NOT do: it never invents an outcome (a point with no faithful
CPython encoding is counted, not guessed), it never emits a test for a point outside the
precondition, and the numbers it reports are counts of tests that ran, not of properties
the model wrote.
"""
